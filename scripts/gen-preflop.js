// Generates src/data/preflop.js: Monte Carlo all-in equity of each of the 169
// starting-hand classes against 1..5 random opponents.
// Usage: node scripts/gen-preflop.js [iterationsPerCell]
import { writeFileSync } from 'node:fs';
import { RANKS, makeCard } from '../src/core/cards.js';
import { quickEquity } from '../src/core/equity.js';
import { RNG } from '../src/core/rng.js';

const ITER = Number(process.argv[2] || 60000);
const rng = new RNG(20261125);
const GR = 'AKQJT98765432';
const out = {};
const t0 = Date.now();
for (let r = 0; r < 13; r++) {
  for (let c = 0; c < 13; c++) {
    const a = GR[r];
    const b = GR[c];
    let label, hole;
    const ra = RANKS.indexOf(a);
    const rb = RANKS.indexOf(b);
    if (r === c) {
      label = a + b;
      hole = [makeCard(ra, 0), makeCard(ra, 1)];
    } else if (r < c) {
      label = a + b + 's';
      hole = [makeCard(ra, 0), makeCard(rb, 0)];
    } else {
      label = b + a + 'o';
      hole = [makeCard(rb, 0), makeCard(ra, 1)];
    }
    out[label] = [1, 2, 3, 4, 5].map((n) => +quickEquity(hole, [], n, ITER, rng).equity.toFixed(4));
  }
}
const se = (0.5 / Math.sqrt(ITER)).toFixed(4);
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(', ')}],`)
  .join('\n');
const file = `// AUTO-GENERATED by scripts/gen-preflop.js — do not edit by hand.
// All-in equity of each starting-hand class vs 1, 2, 3, 4, 5 random opponents.
// Monte Carlo with ${ITER} trials per cell (standard error <= ${se}).
export const PREFLOP_ITERATIONS = ${ITER};
export const PREFLOP_EQUITY = {
${body}
};
`;
writeFileSync(new URL('../src/data/preflop.js', import.meta.url), file);
console.log(`Wrote src/data/preflop.js in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
